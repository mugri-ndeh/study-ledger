"""The study plan: tracks -> units -> steps, taught in order.

Every unit follows the same rhythm:
  learn steps  -> practice -> build (a project from projects.py) -> recap
A track only moves forward one step at a time. A unit can name another unit in
`requires`; the track waits until that unit is finished, so tracks that run in
parallel stay in a sensible order (for example RAG waits for databases).

All resources are free. Paid books are left out on purpose.
"""

from typing import Dict, List, Optional


def r(kind: str, title: str, url: str) -> Dict:
    return {"kind": kind, "title": title, "url": url}


def step(kind: str, title: str, minutes: int, tasks: List[str], done_when: str, resources=()) -> Dict:
    return {"kind": kind, "title": title, "minutes": minutes, "tasks": tasks, "done_when": done_when, "resources": list(resources)}


def learn(title, minutes, tasks, done_when, resources=()):
    return step("learn", title, minutes, tasks, done_when, resources)


def practice(title, minutes, tasks, done_when, resources=()):
    return step("practice", title, minutes, tasks, done_when, resources)


def unit(key: str, title: str, why: str, outcome: str, skills: List[str], steps: List[Dict],
         recap: List[str], build: Optional[str] = None, requires: Optional[str] = None) -> Dict:
    return {"key": key, "title": title, "why": why, "outcome": outcome, "skills": skills,
            "steps": steps, "recap": recap, "build": build, "requires": requires}


def lc(slug: str, title: str, difficulty: str) -> Dict:
    return r("problem", f"{title} · {difficulty}", f"https://leetcode.com/problems/{slug}/")


